$ErrorActionPreference = 'Stop'

$repoRoot  = Split-Path -Parent $PSScriptRoot
$toolsDir  = Join-Path $repoRoot ".tools"
$cliExe    = Join-Path $toolsDir "arduino-cli\arduino-cli.exe"
$cliCfg    = Join-Path $toolsDir "arduino-cli.yaml"
$oldData   = Join-Path $toolsDir "arduino-data"
$fwRoot    = Join-Path $repoRoot "firmware\openpuck-highrate"
$sketch    = Join-Path $fwRoot   "OpenPuck"
$relDir    = Join-Path $repoRoot "firmware\releases"
$scRefresh = Join-Path $repoRoot "src\SteamControllerRefreshRate\bin\Release\net10.0\sc-refresh.exe"

if (-not (Test-Path $cliExe)) {
    throw "arduino-cli not found at $cliExe. Run toolchain setup first."
}
if (-not (Test-Path $scRefresh)) {
    Write-Host "Building sc-refresh..."
    & dotnet build (Join-Path $repoRoot "SteamControllerRefreshRate.sln") -c Release --nologo
}

# Remove any leftover ReparsePoint junctions only (never touch real directories)
foreach ($j in @((Join-Path $env:USERPROFILE ".opk"), (Join-Path $env:USERPROFILE ".opkb"))) {
    if (Test-Path $j) {
        $item = Get-Item -LiteralPath $j -Force -ErrorAction SilentlyContinue
        if ($null -ne $item -and ($item.Attributes -band [System.IO.FileAttributes]::ReparsePoint)) {
            [System.IO.Directory]::Delete($j)
        }
    }
}

# Use real short path ~/.arduino15 (22 chars) so Go EvalSymlinks + arm-none-eabi-gcc stay well under Win32 MAX_PATH (260)
$arduinoData = Join-Path $env:USERPROFILE ".arduino15"
if ((Test-Path (Join-Path $oldData "packages")) -and -not (Test-Path $arduinoData)) {
    # Only relocate into a path that does not exist yet -- NEVER delete a pre-existing user Arduino data dir.
    Write-Host "Relocating Arduino toolchain data to short path $arduinoData..."
    Move-Item -Path $oldData -Destination $arduinoData
}
New-Item -ItemType Directory -Force -Path $arduinoData, $relDir | Out-Null

& $cliExe --config-file $cliCfg config set directories.data $arduinoData | Out-Null
if (-not (Test-Path (Join-Path $arduinoData "packages\adafruit\hardware\nrf52"))) {
    & $cliExe --config-file $cliCfg core install adafruit:nrf52
}

$shortBuild = Join-Path $env:TEMP "opkb"
New-Item -ItemType Directory -Force -Path $shortBuild | Out-Null

$gitHash = "custom"
$prevEap = $ErrorActionPreference
$ErrorActionPreference = 'Continue'
try {
    $h = (& git -C $fwRoot rev-parse --short=8 HEAD 2>$null)
    if ($LASTEXITCODE -eq 0 -and $h) { $gitHash = "$h".Trim() }
} catch {}
$ErrorActionPreference = $prevEap

$puckFwTsHex = "6AC6869B"
try {
    $steamCandidates = @()
    $regSteam = (Get-ItemProperty -Path "HKCU:\Software\Valve\Steam" -Name "SteamPath" -ErrorAction SilentlyContinue).SteamPath
    if ($regSteam) { $steamCandidates += ($regSteam -replace '/', '\') }
    $steamCandidates += @("C:\Program Files (x86)\Steam", "C:\Program Files\Steam")
    foreach ($sp in $steamCandidates) {
        $hwCfg = Join-Path $sp "bin\hardwareupdater\hardwareupdater.cfg"
        if (Test-Path $hwCfg) {
            foreach ($line in [System.IO.File]::ReadAllLines($hwCfg)) {
                if ($line -match '^PROTEUS_FW_TS:([0-9A-Fa-f]{8})\s*$') {
                    $puckFwTsHex = $Matches[1].ToUpperInvariant()
                    break
                }
            }
            break
        }
    }
} catch {}
Write-Host "Using PROTEUS_FW_TS = 0x$puckFwTsHex for OpenPuck ATTR83_PUCK identity"

$linkFlags = "-Wl,--wrap=tud_vendor_control_xfer_cb -Wl,--wrap=tud_descriptor_string_cb -Wl,--wrap=usbd_control_xfer_cb -Wl,--section-start=.rf_journal_guard=0x86000"
$baseUsbFlags = "-DNRF52840_XXAA {build.flags.usb} -DCFG_TUD_HID=6 -DCFG_TUD_TASK_QUEUE_SZ=512 -DCFG_TUD_VENDOR_TX_BUFSIZE=256 -DOPK_RF_JOURNAL_BASE=0x86000 -DOPK_PUCK_FW_TS=0x${puckFwTsHex}u"

$variants = @(
    @{
        Name       = "OpenPuck-1Ctrl-1000Hz"
        VersionTag = "1.1-1kHz"
        PollUs     = "1000u"
        BuildPath  = Join-Path $shortBuild "c1k"
        OutDir     = Join-Path $shortBuild "o1k"
    },
    @{
        Name       = "OpenPuck-1Ctrl-500Hz"
        VersionTag = "1.1-500Hz"
        PollUs     = "2000u"
        BuildPath  = Join-Path $shortBuild "c500"
        OutDir     = Join-Path $shortBuild "o500"
    }
)

$gitVerPath = Join-Path $sketch "git_version.h"
try {
    foreach ($v in $variants) {
        Write-Host ""
        Write-Host "=== Compiling $($v.Name) (POLL_US_DEFAULT=$($v.PollUs)) ==="
        New-Item -ItemType Directory -Force -Path $v.BuildPath, $v.OutDir | Out-Null

        $gitVerHeader = @"
// AUTO-GENERATED by Build-OpenPuckFirmware.ps1 -- do not commit
#pragma once
#define OPK_BUILD_VERSION "$($v.VersionTag)"
#define OPK_GIT_HASH "$gitHash"
#define OPK_GIT_DIRTY 0
"@
        [System.IO.File]::WriteAllText($gitVerPath, $gitVerHeader, [System.Text.UTF8Encoding]::new($false))

        $extraFlags = "$baseUsbFlags -DPOLL_US_DEFAULT=$($v.PollUs)"
        & $cliExe --config-file $cliCfg compile `
            --clean `
            -b adafruit:nrf52:feather52840 `
            --build-path $v.BuildPath `
            --output-dir $v.OutDir `
            --build-property "build.extra_flags=$extraFlags" `
            --build-property "compiler.c.elf.extra_flags=$linkFlags" `
            $sketch

        if ($LASTEXITCODE -ne 0) {
            throw "arduino-cli compile failed for $($v.Name) (exit code $LASTEXITCODE)"
        }

        $hexFile = Join-Path $v.OutDir "OpenPuck.ino.hex"
        $uf2File = Join-Path $relDir "$($v.Name).uf2"
        $hexCopy = Join-Path $relDir "$($v.Name).hex"

        Copy-Item -Path $hexFile -Destination $hexCopy -Force
        & $scRefresh hex2uf2 $hexFile $uf2File 0xADA52840
        if ($LASTEXITCODE -ne 0) {
            throw "UF2 conversion failed for $($v.Name)"
        }
    }
}
finally {
    if (Test-Path $gitVerPath) {
        Remove-Item -Path $gitVerPath -Force -ErrorAction SilentlyContinue
    }
}

$patchFile = Join-Path $repoRoot "firmware\openpuck-highrate-1ctrl.patch"
try {
    $diffText = (& git -C $fwRoot diff) -join "`n"
    if ($diffText) {
        [System.IO.File]::WriteAllText($patchFile, $diffText + "`n", [System.Text.UTF8Encoding]::new($false))
    }
} catch {}

Write-Host ""
Write-Host "=== Firmware Build Complete ==="
Get-ChildItem -Path $relDir -Filter "*.uf2" | Select-Object Name, Length, LastWriteTime

$ErrorActionPreference = 'Stop'

$repoRoot  = Split-Path -Parent $PSScriptRoot
$toolsDir  = Join-Path $repoRoot ".tools"
$cliExe    = Join-Path $toolsDir "arduino-cli\arduino-cli.exe"
$cliCfg    = Join-Path $toolsDir "arduino-cli.yaml"
$fwRoot    = Join-Path $repoRoot "firmware\openpuck-highrate"
$sketch    = Join-Path $fwRoot   "OpenPuck"
$relDir    = Join-Path $repoRoot "firmware\releases"
$scRefresh = Join-Path $repoRoot "src\SteamControllerRefreshRate\bin\Release\net10.0\sc-refresh.exe"

$shortBuild = Join-Path $env:TEMP "opkb-mdk"
New-Item -ItemType Directory -Force -Path $shortBuild, $relDir | Out-Null

function Assert-Uf2AddressBounds {
    param(
        [string]$Uf2Path,
        [uint32]$MinAddr,
        [uint32]$MaxAddrExclusive
    )
    $bytes = [System.IO.File]::ReadAllBytes($Uf2Path)
    if ($bytes.Length -eq 0 -or ($bytes.Length % 512) -ne 0) {
        throw "Invalid UF2 file length in $Uf2Path"
    }
    $blocks = $bytes.Length / 512
    [uint32]$lo = [uint32]::MaxValue
    [uint32]$hi = 0
    for ($i = 0; $i -lt $blocks; $i++) {
        $off = $i * 512
        [uint32]$addr = [BitConverter]::ToUInt32($bytes, $off + 12)
        [uint32]$sz   = [BitConverter]::ToUInt32($bytes, $off + 16)
        if ($addr -lt $lo) { $lo = $addr }
        if (($addr + $sz) -gt $hi) { $hi = $addr + $sz }
    }
    if ($lo -lt $MinAddr -or $hi -gt $MaxAddrExclusive) {
        throw ("UF2 address bounds check failed for {0}: 0x{1:X6}..0x{2:X6} outside [0x{3:X6}, 0x{4:X6})" -f $Uf2Path, $lo, $hi, $MinAddr, $MaxAddrExclusive)
    }
    Write-Host ("  Verified {0}: {1} blocks, range 0x{2:X6}..0x{3:X6}" -f [System.IO.Path]::GetFileName($Uf2Path), $blocks, $lo, $hi)
}

function Build-MdkVariant {
    param(
        [int]$Hz,
        [uint32]$PollUs,
        [string]$VerTag,
        [string]$HashTag,
        [bool]$EmitFirstInstall
    )

    $buildPath = Join-Path $shortBuild "b-$Hz"
    $outDir    = Join-Path $shortBuild "o-$Hz"
    New-Item -ItemType Directory -Force -Path $buildPath, $outDir | Out-Null

    $gitVerPath = Join-Path $sketch "git_version.h"
    $gitVerHeader = @"
// AUTO-GENERATED by Build-MDK-FirstInstall.ps1 -- do not commit
#pragma once
#define OPK_BUILD_VERSION "$VerTag"
#define OPK_GIT_HASH "$HashTag"
#define OPK_GIT_DIRTY 0
"@
    [System.IO.File]::WriteAllText($gitVerPath, $gitVerHeader, [System.Text.UTF8Encoding]::new($false))

    try {
        $puckFwTsHex = "6AC6869B"
        $linkFlags = "-Wl,--wrap=tud_vendor_control_xfer_cb -Wl,--wrap=tud_descriptor_string_cb -Wl,--wrap=usbd_control_xfer_cb -Wl,--section-start=.rf_journal_guard=0x86000"
        $extraFlags = "-DNRF52840_XXAA {build.flags.usb} -DCFG_TUD_HID=6 -DCFG_TUD_TASK_QUEUE_SZ=512 -DCFG_TUD_VENDOR_TX_BUFSIZE=256 -DOPK_RF_JOURNAL_BASE=0x86000 -DOPK_PUCK_FW_TS=0x${puckFwTsHex}u -DOPK_BOARD_MDK_USB_DONGLE=1 -DPOLL_US_DEFAULT=${PollUs}u"

        Write-Host "Compiling OpenPuck for Makerdiary/GeeekPi MDK ($Hz Hz / $PollUs us)..."
        & $cliExe --config-file $cliCfg compile `
            --clean `
            -b adafruit:nrf52:feather52840 `
            --build-path $buildPath `
            --output-dir $outDir `
            --build-property "build.extra_flags=$extraFlags" `
            --build-property "compiler.c.elf.extra_flags=$linkFlags" `
            $sketch

        if ($LASTEXITCODE -ne 0) {
            throw "arduino-cli compile failed for MDK $Hz Hz (exit code $LASTEXITCODE)"
        }

        $appHex = Join-Path $outDir "OpenPuck.ino.hex"
        $appOnlyUf2 = Join-Path $relDir "OpenPuck-MDK-${Hz}Hz.uf2"

        Write-Host "Converting App-Only UF2 ($appOnlyUf2)..."
        & $scRefresh hex2uf2 $appHex $appOnlyUf2 0xADA52840
        if ($LASTEXITCODE -ne 0) {
            throw "UF2 conversion failed for $appOnlyUf2"
        }
        Assert-Uf2AddressBounds -Uf2Path $appOnlyUf2 -MinAddr 0x26000 -MaxAddrExclusive 0x86000

        if ($EmitFirstInstall) {
            $sdHex  = Join-Path $relDir "s140_nrf52_6.1.1.hex"
            $mergedHex = Join-Path $relDir "OpenPuck-MDK-FirstInstall-${Hz}Hz.hex"
            $firstInstallUf2 = Join-Path $relDir "OpenPuck-MDK-FirstInstall-${Hz}Hz.uf2"

            Write-Host "Merging S140 6.1.1 SoftDevice + OpenPuck MDK Application..."
            $sdLines = [System.IO.File]::ReadAllLines($sdHex) | Where-Object { -not $_.StartsWith(":00000001FF") }
            $appLines = [System.IO.File]::ReadAllLines($appHex)
            $allLines = [System.Collections.Generic.List[string]]::new()
            foreach ($l in $sdLines) { $allLines.Add($l) }
            foreach ($l in $appLines) { $allLines.Add($l) }
            [System.IO.File]::WriteAllLines($mergedHex, $allLines)

            Write-Host "Converting to FirstInstall UF2 ($firstInstallUf2)..."
            & $scRefresh hex2uf2 $mergedHex $firstInstallUf2 0xADA52840
            if ($LASTEXITCODE -ne 0) {
                throw "UF2 conversion failed for $firstInstallUf2"
            }
            Assert-Uf2AddressBounds -Uf2Path $firstInstallUf2 -MinAddr 0x00000 -MaxAddrExclusive 0x86000
        }
    }
    finally {
        if (Test-Path $gitVerPath) {
            Remove-Item -Path $gitVerPath -Force -ErrorAction SilentlyContinue
        }
    }
}

Build-MdkVariant -Hz 1000 -PollUs 1000 -VerTag "1.1-MDK-1kHz" -HashTag "mdk1k1" -EmitFirstInstall $true
Build-MdkVariant -Hz 500  -PollUs 2000 -VerTag "1.1-MDK-500"  -HashTag "mdk500" -EmitFirstInstall $false

Write-Host "`nAll MDK firmware artifacts built successfully:"
Get-Item (Join-Path $relDir "OpenPuck-MDK-*.uf2") | Select-Object Name, Length, LastWriteTime
